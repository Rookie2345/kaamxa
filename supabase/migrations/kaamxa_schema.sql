create function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false)
$$;

create function public.is_job_owner(j uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.jobs where id = j and employer_id = auth.uid())
$$;

create function public.has_applied(j uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.applications where job_id = j and applicant_id = auth.uid())
$$;

create function public.owns_question(q uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.job_questions jq
    join public.jobs j on j.id = jq.job_id
    where jq.id = q and j.employer_id = auth.uid())
$$;

create function public.can_see_application(a uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.applications ap
    join public.jobs j on j.id = ap.job_id
    where ap.id = a and (ap.applicant_id = auth.uid() or j.employer_id = auth.uid()))
$$;

create function public.is_applicant(a uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.applications where id = a and applicant_id = auth.uid())
$$;

create function public.is_participant(c uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.conversations
                 where id = c and auth.uid() in (user_a, user_b))
$$;

-- True if two users share a chat or an application (used to reveal phone numbers)
create function public.shares_context(a uuid, b uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.conversations c
                 where c.user_a = least(a, b) and c.user_b = greatest(a, b))
      or exists (select 1 from public.applications ap
                 join public.jobs j on j.id = ap.job_id
                 where (ap.applicant_id = a and j.employer_id = b)
                    or (ap.applicant_id = b and j.employer_id = a))
$$;

-- Internal flag so our own triggers/RPCs may change protected columns
create function public.bypass_on() returns void language sql as $$
  select set_config('app.bypass', '1', true)
$$;
create function public.bypass_off() returns void language sql as $$
  select set_config('app.bypass', '0', true)
$$;
create function public.bypassing() returns boolean language sql stable as $$
  select coalesce(current_setting('app.bypass', true), '0') = '1'
$$;

