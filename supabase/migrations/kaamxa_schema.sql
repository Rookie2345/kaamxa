-- ---------- 1. Types ----------
create type pay_type        as enum ('hour','day','month','job');
create type job_status      as enum ('open','filled','closed','expired');
create type app_status      as enum ('applied','shortlisted','rejected','hired','withdrawn');
create type question_kind   as enum ('mcq','text');
create type hire_status     as enum ('active','completed','cancelled');
create type report_reason   as enum ('spam','fake','foreign_job','asks_money','abuse','other');

-- ---------- 2. Reference tables (read-only for users) ----------
create table provinces (
  id      smallint primary key,
  name_en text not null,
  name_ne text not null
);

create table districts (
  id          smallint generated by default as identity primary key,
  province_id smallint not null references provinces(id),
  name_en     text not null,
  name_ne     text not null
);

-- Municipalities start empty. Add them gradually (district_id, name, kind).
create table municipalities (
  id          int generated by default as identity primary key,
  district_id smallint not null references districts(id),
  name_en     text not null,
  name_ne     text not null,
  kind        text check (kind in ('metropolitan','sub-metropolitan','municipality','rural municipality'))
);

create table trades (
  slug    text primary key,
  name_en text not null,
  name_ne text not null,
  sort    smallint not null default 100
);

create table question_templates (
  id            int generated by default as identity primary key,
  trade_slug    text references trades(slug),   -- null = general question for any trade
  kind          question_kind not null,
  question_en   text not null,
  question_ne   text not null,
  options_en    jsonb,
  options_ne    jsonb,
  correct_index smallint
);

-- ---------- 3. Users ----------
create table profiles (
  id              uuid primary key references auth.users(id) on delete cascade,
  full_name       text not null default '',
  avatar_url      text,
  district_id     smallint references districts(id),
  municipality_id int references municipalities(id),
  tole            text,
  language        text not null default 'ne' check (language in ('ne','en')),
  is_admin        boolean not null default false,
  is_hidden       boolean not null default false,
  report_count    int not null default 0,
  rating_avg      numeric(3,2) not null default 0,
  rating_count    int not null default 0,
  completed_jobs  int not null default 0,
  created_at      timestamptz not null default now()
);

-- Phone numbers live apart from the public profile and are only shown to
-- people who share a chat or an application with the owner.
create table profile_contacts (
  user_id  uuid primary key references profiles(id) on delete cascade,
  phone    text not null check (phone ~ '^(\+977)?9[78][0-9]{8}$'),
  whatsapp text check (whatsapp is null or whatsapp ~ '^(\+977)?9[78][0-9]{8}$')
);

create table worker_details (
  user_id          uuid primary key references profiles(id) on delete cascade,
  headline         text check (char_length(headline) <= 120),
  bio              text check (char_length(bio) <= 1000),
  skills           text[] not null default '{}',          -- trade slugs
  experience_years smallint check (experience_years between 0 and 60),
  available        boolean not null default true,
  photos           text[] not null default '{}' check (coalesce(array_length(photos,1),0) <= 6),
  updated_at       timestamptz not null default now()
);

-- ---------- 4. Jobs ----------
create table jobs (
  id              uuid primary key default gen_random_uuid(),
  employer_id     uuid not null references profiles(id) on delete cascade,
  title           text not null check (char_length(title) between 3 and 120),
  description     text not null default '' check (char_length(description) <= 3000),
  trade_slug      text not null references trades(slug),
  district_id     smallint not null references districts(id),
  municipality_id int references municipalities(id),
  tole            text,
  pay_type        pay_type not null,
  pay_min         numeric(10,2) check (pay_min >= 0),
  pay_max         numeric(10,2) check (pay_max >= 0),
  negotiable      boolean not null default false,
  positions       smallint not null default 1 check (positions between 1 and 100),
  filled          smallint not null default 0,
  status          job_status not null default 'open',
  is_hidden       boolean not null default false,
  report_count    int not null default 0,
  expires_at      timestamptz not null default (now() + interval '30 days'),
  created_at      timestamptz not null default now(),
  check (pay_max is null or pay_min is null or pay_max >= pay_min)
);

create index jobs_browse_idx on jobs (status, district_id, trade_slug, created_at desc);
create index jobs_employer_idx on jobs (employer_id);
create index jobs_search_idx on jobs using gin (to_tsvector('simple', title || ' ' || description));

-- Employer-defined screening (max 5 questions per job)
create table job_questions (
  id       uuid primary key default gen_random_uuid(),
  job_id   uuid not null references jobs(id) on delete cascade,
  position smallint not null check (position between 1 and 5),
  kind     question_kind not null,
  question text not null check (char_length(question) <= 300),
  options  jsonb,                       -- for mcq: ["A","B","C","D"]
  unique (job_id, position)
);

-- Correct answers are kept in a separate table only the employer can read,
-- so applicants cannot see them.
create table job_question_keys (
  question_id   uuid primary key references job_questions(id) on delete cascade,
  correct_index smallint not null check (correct_index between 0 and 5)
);

create table applications (
  id           uuid primary key default gen_random_uuid(),
  job_id       uuid not null references jobs(id) on delete cascade,
  applicant_id uuid not null references profiles(id) on delete cascade,
  status       app_status not null default 'applied',
  message      text check (char_length(message) <= 500),
  score        smallint not null default 0,
  max_score    smallint not null default 0,
  created_at   timestamptz not null default now(),
  unique (job_id, applicant_id)
);
create index applications_job_idx on applications (job_id, status);
create index applications_user_idx on applications (applicant_id, created_at desc);

create table application_answers (
  id             uuid primary key default gen_random_uuid(),
  application_id uuid not null references applications(id) on delete cascade,
  question_id    uuid not null references job_questions(id) on delete cascade,
  answer_text    text check (char_length(answer_text) <= 1000),
  answer_index   smallint,
  is_correct     boolean,
  unique (application_id, question_id)
);

-- ---------- 5. Hires and reviews ----------
create table hires (
  id             uuid primary key default gen_random_uuid(),
  job_id         uuid not null references jobs(id) on delete cascade,
  application_id uuid not null unique references applications(id) on delete cascade,
  employer_id    uuid not null references profiles(id),
  worker_id      uuid not null references profiles(id),
  status         hire_status not null default 'active',
  created_at     timestamptz not null default now(),
  completed_at   timestamptz
);

create table reviews (
  id          uuid primary key default gen_random_uuid(),
  hire_id     uuid not null references hires(id) on delete cascade,
  reviewer_id uuid not null references profiles(id) on delete cascade,
  reviewee_id uuid not null references profiles(id) on delete cascade,
  rating      smallint not null check (rating between 1 and 5),
  comment     text check (char_length(comment) <= 500),
  created_at  timestamptz not null default now(),
  unique (hire_id, reviewer_id)
);
create index reviews_reviewee_idx on reviews (reviewee_id, created_at desc);

-- ---------- 6. Chat ----------
create table conversations (
  id         uuid primary key default gen_random_uuid(),
  user_a     uuid not null references profiles(id) on delete cascade,
  user_b     uuid not null references profiles(id) on delete cascade,
  job_id     uuid references jobs(id) on delete set null,
  created_at timestamptz not null default now(),
  check (user_a < user_b),
  unique (user_a, user_b)
);

create table messages (
  id              bigint generated always as identity primary key,
  conversation_id uuid not null references conversations(id) on delete cascade,
  sender_id       uuid not null references profiles(id) on delete cascade,
  body            text not null check (char_length(body) between 1 and 2000),
  created_at      timestamptz not null default now(),
  read_at         timestamptz
);
create index messages_conv_idx on messages (conversation_id, created_at);

-- ---------- 7. Reports ----------
create table reports (
  id          uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references profiles(id) on delete cascade,
  job_id      uuid references jobs(id) on delete cascade,
  profile_id  uuid references profiles(id) on delete cascade,
  reason      report_reason not null,
  details     text check (char_length(details) <= 500),
  created_at  timestamptz not null default now(),
  check ((job_id is not null)::int + (profile_id is not null)::int = 1)
);
create unique index reports_one_per_job     on reports (reporter_id, job_id)     where job_id is not null;
create unique index reports_one_per_profile on reports (reporter_id, profile_id) where profile_id is not null;

