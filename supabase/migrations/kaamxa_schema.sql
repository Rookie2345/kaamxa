-- Employer hires an applicant
create function public.hire_applicant(app_id uuid) returns uuid
language plpgsql security definer set search_path = public as $$
declare a public.applications; j public.jobs; hid uuid;
begin
  select * into a from public.applications where id = app_id;
  if not found then raise exception 'Application not found.'; end if;
  select * into j from public.jobs where id = a.job_id;
  if j.employer_id <> auth.uid() then raise exception 'Only the employer can hire.'; end if;
  if a.status not in ('applied','shortlisted') then raise exception 'This applicant cannot be hired.'; end if;
  if j.filled >= j.positions then raise exception 'All positions are already filled.'; end if;

  perform public.bypass_on();
  update public.applications set status = 'hired' where id = app_id;
  insert into public.hires (job_id, application_id, employer_id, worker_id)
    values (j.id, a.id, j.employer_id, a.applicant_id) returning id into hid;
  update public.jobs set
    filled = filled + 1,
    status = case when filled + 1 >= positions then 'filled'::job_status else status end
  where id = j.id;
  perform public.bypass_off();
  return hid;
end $$;

-- Employer marks the work as done (this unlocks reviews)
create function public.complete_hire(hire_id uuid) returns void
language plpgsql security definer set search_path = public as $$
declare h public.hires;
begin
  select * into h from public.hires where id = hire_id;
  if not found or h.employer_id <> auth.uid() then raise exception 'Not allowed.'; end if;
  if h.status <> 'active' then raise exception 'This hire is already closed.'; end if;
  perform public.bypass_on();
  update public.hires set status = 'completed', completed_at = now() where id = hire_id;
  update public.profiles set completed_jobs = completed_jobs + 1
    where id in (h.employer_id, h.worker_id);
  perform public.bypass_off();
end $$;

-- Start or reuse a chat with another user
create function public.get_or_create_conversation(other uuid, for_job uuid default null) returns uuid
language plpgsql security definer set search_path = public as $$
declare cid uuid; me uuid := auth.uid();
begin
  if me is null then raise exception 'Please log in.'; end if;
  if other = me then raise exception 'You cannot chat with yourself.'; end if;
  select id into cid from public.conversations
    where user_a = least(me, other) and user_b = greatest(me, other);
  if cid is null then
    insert into public.conversations (user_a, user_b, job_id)
      values (least(me, other), greatest(me, other), for_job) returning id into cid;
  end if;
  return cid;
end $$;

create function public.mark_read(conv uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_participant(conv) then raise exception 'Not allowed.'; end if;
  update public.messages set read_at = now()
    where conversation_id = conv and sender_id <> auth.uid() and read_at is null;
end $$;

-- Admin: restore an auto-hidden job or profile and clear its reports
create function public.admin_restore(kind text, target uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Admins only.'; end if;
  perform public.bypass_on();
  if kind = 'job' then
    update public.jobs set is_hidden = false, report_count = 0 where id = target;
    delete from public.reports where job_id = target;
  elsif kind = 'profile' then
    update public.profiles set is_hidden = false, report_count = 0 where id = target;
    delete from public.reports where profile_id = target;
  end if;
  perform public.bypass_off();
end $$;

-- Mark old jobs as expired (public queries already ignore expired jobs,
-- this just keeps the status column tidy)
create function public.expire_jobs() returns void
language sql security definer set search_path = public as $$
  update public.jobs set status = 'expired' where status = 'open' and expires_at < now()
$$;

