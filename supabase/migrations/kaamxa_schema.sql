-- 9.1 Create a profile row for every new auth user
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name',
                           new.raw_user_meta_data->>'name', ''))
  on conflict (id) do nothing;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- 9.2 Users cannot edit protected profile columns
create function public.protect_profile() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if public.bypassing() or auth.uid() is null or public.is_admin() then return new; end if;
  new.is_admin       := old.is_admin;
  new.is_hidden      := old.is_hidden;
  new.report_count   := old.report_count;
  new.rating_avg     := old.rating_avg;
  new.rating_count   := old.rating_count;
  new.completed_jobs := old.completed_jobs;
  return new;
end $$;
create trigger trg_protect_profile before update on profiles
  for each row execute function public.protect_profile();

-- 9.3 Users cannot edit protected job columns
create function public.protect_job() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if public.bypassing() or auth.uid() is null or public.is_admin() then return new; end if;
  new.employer_id  := old.employer_id;
  new.is_hidden    := old.is_hidden;
  new.report_count := old.report_count;
  new.filled       := old.filled;
  new.expires_at   := old.expires_at;
  new.created_at   := old.created_at;
  return new;
end $$;
create trigger trg_protect_job before update on jobs
  for each row execute function public.protect_job();

-- 9.4 Block foreign-employment posts and "pay us a fee" posts
create function public.screen_job_text() returns trigger
language plpgsql as $$
declare t text := lower(new.title || ' ' || new.description);
begin
  if t ~ '(foreign employment|abroad|malaysia|qatar|dubai|saudi|kuwait|\muae\M|korea|work visa|manpower|वैदेशिक|विदेश|खाडी|मलेसिया|कतार|दुबई)' then
    raise exception 'KaamXa only allows jobs inside Nepal. Foreign-employment posts are not allowed.';
  end if;
  if t ~ '(registration fee|processing fee|security deposit|advance payment|pay us|pay first|joining fee|शुल्क तिर्नु|अग्रिम भुक्तानी|धरौटी)' then
    raise exception 'Jobs that ask workers to pay money are not allowed.';
  end if;
  return new;
end $$;
create trigger trg_screen_job_text before insert or update of title, description on jobs
  for each row execute function public.screen_job_text();

-- 9.5 Rate limits (columns: owner column, window, max)
create function public.enforce_rate_limit() returns trigger
language plpgsql security definer set search_path = public as $$
declare uid uuid; n int;
begin
  uid := (to_jsonb(new) ->> tg_argv[0])::uuid;
  execute format('select count(*) from public.%I where %I = $1 and created_at > now() - $2::interval',
                 tg_table_name, tg_argv[0])
    into n using uid, tg_argv[1];
  if n >= tg_argv[2]::int then
    raise exception 'Too many requests. Please try again later.';
  end if;
  return new;
end $$;

create trigger rl_jobs         before insert on jobs         for each row execute function public.enforce_rate_limit('employer_id','1 day',5);
create trigger rl_applications before insert on applications for each row execute function public.enforce_rate_limit('applicant_id','1 day',30);
create trigger rl_messages     before insert on messages     for each row execute function public.enforce_rate_limit('sender_id','10 minutes',60);
create trigger rl_reports      before insert on reports      for each row execute function public.enforce_rate_limit('reporter_id','1 day',20);

-- 9.6 Applications: only to open jobs, never your own
create function public.check_application() returns trigger
language plpgsql security definer set search_path = public as $$
declare j public.jobs;
begin
  select * into j from public.jobs where id = new.job_id;
  if not found or j.status <> 'open' or j.is_hidden or j.expires_at <= now() then
    raise exception 'This job is not open for applications.';
  end if;
  if j.employer_id = new.applicant_id then
    raise exception 'You cannot apply to your own job.';
  end if;
  new.status := 'applied';
  new.score := 0;
  new.max_score := 0;
  return new;
end $$;
create trigger trg_check_application before insert on applications
  for each row execute function public.check_application();

-- 9.7 Application status rules
create function public.guard_application_update() returns trigger
language plpgsql security definer set search_path = public as $$
declare owner uuid;
begin
  if public.bypassing() or auth.uid() is null then return new; end if;
  select employer_id into owner from public.jobs where id = old.job_id;
  new.job_id       := old.job_id;
  new.applicant_id := old.applicant_id;
  new.score        := old.score;
  new.max_score    := old.max_score;
  new.message      := old.message;
  if new.status = old.status then return new; end if;

  if auth.uid() = old.applicant_id then
    if new.status = 'withdrawn' and old.status in ('applied','shortlisted') then return new; end if;
    raise exception 'Applicants can only withdraw an application.';
  elsif auth.uid() = owner then
    if new.status in ('shortlisted','rejected') and old.status in ('applied','shortlisted','rejected') then return new; end if;
    raise exception 'Use the hire action to hire someone.';
  end if;
  raise exception 'Not allowed.';
end $$;
create trigger trg_guard_application before update on applications
  for each row execute function public.guard_application_update();

-- 9.8 Auto-score screening answers
create function public.score_answer() returns trigger
language plpgsql security definer set search_path = public as $$
declare q public.job_questions; a public.applications; k smallint;
begin
  select * into a from public.applications where id = new.application_id;
  select * into q from public.job_questions where id = new.question_id;
  if q.job_id is distinct from a.job_id then
    raise exception 'That question does not belong to this job.';
  end if;
  if a.status <> 'applied' then
    raise exception 'Answers can no longer be changed.';
  end if;
  if q.kind = 'mcq' then
    select correct_index into k from public.job_question_keys where question_id = q.id;
    new.is_correct  := (k is not null and new.answer_index = k);
    new.answer_text := null;
  else
    new.is_correct   := null;
    new.answer_index := null;
  end if;
  return new;
end $$;
create trigger trg_score_answer before insert on application_answers
  for each row execute function public.score_answer();

create function public.recount_score() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  perform public.bypass_on();
  update public.applications ap set
    score = (select count(*) from public.application_answers aa
             where aa.application_id = ap.id and aa.is_correct),
    max_score = (select count(*) from public.job_questions jq
                 where jq.job_id = ap.job_id and jq.kind = 'mcq')
  where ap.id = new.application_id;
  perform public.bypass_off();
  return null;
end $$;
create trigger trg_recount_score after insert on application_answers
  for each row execute function public.recount_score();

-- 9.9 Reviews: only after a completed hire, only between the two parties
create function public.check_review() returns trigger
language plpgsql security definer set search_path = public as $$
declare h public.hires;
begin
  select * into h from public.hires where id = new.hire_id;
  if not found or h.status <> 'completed' then
    raise exception 'You can review only after the job is marked complete.';
  end if;
  if new.reviewer_id not in (h.employer_id, h.worker_id) then
    raise exception 'Only the employer and the worker can review each other.';
  end if;
  new.reviewee_id := case when new.reviewer_id = h.employer_id then h.worker_id else h.employer_id end;
  return new;
end $$;
create trigger trg_check_review before insert on reviews
  for each row execute function public.check_review();

create function public.update_rating() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  perform public.bypass_on();
  update public.profiles p set
    rating_avg   = coalesce((select round(avg(rating)::numeric, 2) from public.reviews where reviewee_id = new.reviewee_id), 0),
    rating_count = (select count(*) from public.reviews where reviewee_id = new.reviewee_id)
  where p.id = new.reviewee_id;
  perform public.bypass_off();
  return null;
end $$;
create trigger trg_update_rating after insert on reviews
  for each row execute function public.update_rating();

-- 9.10 Reports: 3 different reporters hide the job or profile automatically
create function public.handle_report() returns trigger
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  perform public.bypass_on();
  if new.job_id is not null then
    if exists (select 1 from public.jobs where id = new.job_id and employer_id = new.reporter_id) then
      raise exception 'You cannot report your own job.';
    end if;
    select count(distinct reporter_id) into n from public.reports where job_id = new.job_id;
    update public.jobs set report_count = n, is_hidden = (is_hidden or n >= 3) where id = new.job_id;
  else
    if new.profile_id = new.reporter_id then
      raise exception 'You cannot report yourself.';
    end if;
    select count(distinct reporter_id) into n from public.reports where profile_id = new.profile_id;
    update public.profiles set report_count = n, is_hidden = (is_hidden or n >= 3) where id = new.profile_id;
  end if;
  perform public.bypass_off();
  return null;
end $$;
create trigger trg_handle_report after insert on reports
  for each row execute function public.handle_report();

